#!/bin/sh
# gen-darwin-modulemap.sh SYSROOT CC TARGET: writes SYSROOT/usr/include/module.modulemap,
# a Darwin clang module with one submodule per self-contained libc/POSIX/Mach header
set -e
R=$1
CC=$2
T=$3
cd "$R/usr/include"

# kernel-private, ObjC, dispatch and arch-foreign trees belong to other modules or none
skip='^(module|pd_|puredarwin|objc/|dispatch/|os/|xpc/|c\+\+/|libxml2/|CoreEntitlements/|CodeSignature/|TrustCache/|corecrypto/|image4/|img4/|CommonCrypto/|libDER/|security_libDER/|secure/|acpi/|System/|uuid/|device/|bsm/|servers/|arm|riscv|x86_64/|.*_private\.h|.*_priv\.h|.*_internal\.h|.*Private.*|asl_|launch_|vproc|bootstrap_priv|dlfcn_private|Block_private|AvailabilityInternal|AvailabilityProhibited|string_x86|openlibm_|cdefs-compat|types-compat|aliasdb|printerdb|mach_debug/|.*legacy.*)'
list=$( (ls *.h sys/_types/*.h _types/*.h i386/*.h sys/*.h mach/*.h mach/machine/*.h machine/*.h \
  netinet/*.h netinet6/*.h arpa/*.h net/*.h mach-o/*.h malloc/*.h libkern/*.h libkern/i386/*.h 2>/dev/null) \
  | grep -Ev "$skip" | sort -u)

ok=""
for h in $list; do
  [ -f "$h" ] || continue
  out=$(echo "#include <$h>" | $CC -x objective-c -fsyntax-only -H -target "$T" -isysroot "$R" - 2>&1) || continue
  echo "$out" | grep -qE "error:|_private\.h|pfvar\.h|/asm\.h|/(objc|dispatch|xpc)/|os/object.h|CoreFoundation" && continue
  ok="$ok $h"
done

# compiler builtin headers, pairwise-conflicting headers and kernel-only net headers stay out
drop='^(stdarg|stdbool|stddef|stdatomic|iso646|float|stdalign|tgmath|stdnoreturn|unwind|varargs|nlist|ranlib|sys/disklabel|sys/disktab|disktab|net/if_var_status|mach-o/dyld_process_info|net/multi_layer_pkt_log|net/if_var|net/kpi_interface|net/if_var_private)\.h$'
{
  echo "// generated by gen-darwin-modulemap.sh"
  echo "module Darwin [system] [extern_c] {"
  for h in $ok; do
    echo "$h" | grep -qE "$drop" && continue
    n=$(echo "$h" | sed 's/\.h$//; s/[^A-Za-z0-9]/_/g')
    req=
    case $h in *i386/*) req="requires x86 " ;; esac
    echo "  module $n { ${req}header \"$h\" export * }"
  done
  echo "  export *"
  echo "}"
} > module.modulemap
